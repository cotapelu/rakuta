#!/usr/bin/env node
/**
 * system.audit capability
 *
 * Performs a basic system audit: lint, security, typecheck.
 * Returns a markdown report.
 */

import { Type } from "typebox";

export const schema = Type.Object({
  // No parameters for now
}, { additionalProperties: false });

export async function execute(params: any, ctx: any): Promise<any> {
  const cwd = ctx.cwd || process.cwd();

  try {
    // Run lint
    let lintResult: { code: number; stdout: string; stderr: string };
    try {
      lintResult = await ctx.exec('npm', ['run', 'lint'], { cwd });
    } catch (err: any) {
      lintResult = { code: err.code || 1, stdout: err.stdout || '', stderr: err.stderr || String(err) };
    }
    const lintOutput = (lintResult.stdout + lintResult.stderr).trim();
    const hasLintErrors = lintResult.code !== 0 || /\berror\b/i.test(lintOutput);
    const lintSummary = hasLintErrors
      ? `❌ Lint errors detected:\n${lintOutput || 'See output'}`
      : `✅ No lint errors`;

    // Run typecheck
    let typecheckResult: { code: number; stdout: string; stderr: string };
    try {
      typecheckResult = await ctx.exec('npm', ['run', 'typecheck'], { cwd });
    } catch (err: any) {
      typecheckResult = { code: err.code || 1, stdout: err.stdout || '', stderr: err.stderr || String(err) };
    }
    const typecheckOutput = (typecheckResult.stdout + typecheckResult.stderr).trim();
    const hasTypeErrors = typecheckResult.code !== 0;
    const typecheckSummary = hasTypeErrors
      ? `❌ Type errors detected:\n${typecheckOutput || 'See output'}`
      : `✅ No type errors`;

    // Run security audit (high severity)
    let auditResult: { code: number; stdout: string; stderr: string };
    try {
      auditResult = await ctx.exec('npm', ['audit', '--audit-level=high'], { cwd });
    } catch (err: any) {
      auditResult = { code: err.code || 1, stdout: err.stdout || '', stderr: err.stderr || String(err) };
    }
    const auditOutput = (auditResult.stdout + auditResult.stderr).trim();
    const hasVulns = auditResult.code !== 0;
    const auditSummary = hasVulns
      ? `❌ High severity vulnerabilities found:\n${auditOutput || 'See output'}`
      : `✅ No high severity vulnerabilities`;

    // Compile report
    const report = `# System Audit Report

## Summary
- Lint: ${hasLintErrors ? 'FAIL' : 'PASS'}
- Type Check: ${hasTypeErrors ? 'FAIL' : 'PASS'}
- Security Audit: ${hasVulns ? 'FAIL' : 'PASS'}

## Details

### Lint
${lintSummary}

### Type Check
${typecheckSummary}

### Security Audit
${auditSummary}

---
*Generated by PiClaw System Audit capability*
`;
    const isError = hasLintErrors || hasTypeErrors || hasVulns;

    return {
      content: [{ type: 'text', text: report }],
      details: {
        lint: { code: lintResult.code },
        typecheck: { code: typecheckResult.code },
        audit: { code: auditResult.code },
      },
      isError,
    };
  } catch (error: unknown) {
    const msg = error instanceof Error ? error.message : String(error);
    return { content: [{ type: 'text', text: `❌ Audit execution error: ${msg}` }], isError: true, details: { error: msg } };
  }
}

export default { execute, schema };
